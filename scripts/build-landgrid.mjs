// Downsample the land mask to a 360×180 grid (1°) of signed coast distance for the agent sims.
// Output: src/data/landgrid.ts (base64 Uint8: 128 = coast, >128 land, <128 sea).
import fs from 'node:fs';
import zlib from 'node:zlib';
function decodePNG(buf) {
  let pos = 8, w = 0, h = 0;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos);
    const type = buf.toString('ascii', pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if (type === 'IHDR') { w = data.readUInt32BE(0); h = data.readUInt32BE(4); }
    if (type === 'IDAT') idat.push(data);
    pos += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const ch = 4, stride = w * ch, out = new Uint8Array(w * h * ch);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)];
    for (let x = 0; x < stride; x++) {
      const v = raw[y * (stride + 1) + 1 + x];
      const a = x >= ch ? out[y * stride + x - ch] : 0, b = y > 0 ? out[(y - 1) * stride + x] : 0, c = x >= ch && y > 0 ? out[(y - 1) * stride + x - ch] : 0;
      let r;
      if (f === 0) r = v; else if (f === 1) r = v + a; else if (f === 2) r = v + b; else if (f === 3) r = v + ((a + b) >> 1);
      else { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); r = v + (pa <= pb && pa <= pc ? a : pb <= pc ? b : c); }
      out[y * stride + x] = r & 255;
    }
  }
  return { w, h, data: out };
}
const m = decodePNG(fs.readFileSync(new URL('../src/assets/earth/landmask.png', import.meta.url)));
const W = 360, H = 180;
const g = new Uint8Array(W * H);
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  // sample the centre of each 1° cell (row 0 = 89.5°N)
  const mx = Math.floor(((x + 0.5) / W) * m.w), my = Math.floor(((y + 0.5) / H) * m.h);
  g[y * W + x] = m.data[(my * m.w + mx) * 4];
}
const b64 = Buffer.from(g).toString('base64');
fs.writeFileSync(new URL('../src/data/landgrid.ts', import.meta.url), `// Generated by scripts/build-landgrid.mjs from the Natural Earth land mask. Do not edit.\n// 360×180 cells (1°), row 0 = 89.5°N, col 0 = 179.5°W. 128 = coast, >128 land.\nexport const LAND_W = 360;\nexport const LAND_H = 180;\nexport const LAND_B64 = '${b64}';\n\nlet grid: Uint8Array | null = null;\nexport function landGrid(): Uint8Array {\n  if (grid) return grid;\n  const bin = atob(LAND_B64);\n  grid = new Uint8Array(bin.length);\n  for (let i = 0; i < bin.length; i++) grid[i] = bin.charCodeAt(i);\n  return grid;\n}\n\n/** signed coast value at lat/lon in [-1, 1] (positive = land) */\nexport function landAt(lat: number, lon: number): number {\n  const g = landGrid();\n  const y = Math.max(0, Math.min(LAND_H - 1, Math.floor(90 - lat)));\n  const x = ((Math.floor(lon + 180) % LAND_W) + LAND_W) % LAND_W;\n  return (g[y * LAND_W + x]! - 128) / 127;\n}\n`);
